#!/usr/bin/env bash
#
# Deploy MASAR. Idempotent, and it refuses rather than guesses.
#
# Assets are NOT built here. They are built locally and committed, so the commit
# and the served bundle cannot disagree — see the note in .gitignore. If the
# build is missing or stale against the sources, this stops.
#
#   usage:  deploy/deploy.sh [git-ref]
#
set -Eeuo pipefail

APP_DIR="${MASAR_APP_DIR:-/var/www/masar}"
PHP="${MASAR_PHP:-php}"
REF="${1:-origin/main}"

log()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m !\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31mxxx\033[0m %s\n' "$*" >&2; exit 1; }

trap 'die "deploy failed on line $LINENO — the site is still on the previous release"' ERR

cd "$APP_DIR" || die "no app directory at $APP_DIR"

# ---------------------------------------------------------------- preflight --
[[ -f artisan ]]        || die "not a Laravel root: $APP_DIR"
[[ -f .env ]]           || die ".env missing — never generated by this script"
command -v "$PHP" >/dev/null || die "php not on PATH"

php_version="$("$PHP" -r 'echo PHP_VERSION;')"
"$PHP" -r 'exit(version_compare(PHP_VERSION, "8.4.1", ">=") ? 0 : 1);' \
  || die "PHP $php_version is too old — composer.json pins the platform to 8.4.1"

grep -q '^APP_ENV=production'  .env || warn "APP_ENV is not production"
grep -q '^APP_DEBUG=false'     .env || die  "APP_DEBUG must be false in production"

log "deploying $REF onto PHP $php_version"

# ------------------------------------------------------------------- source --
git fetch --all --prune
git reset --hard "$REF"

# The built bundle is committed. If it is absent the site serves no CSS at all,
# which looks like a styling bug and is actually a missing deploy step.
[[ -f public/build/manifest.json ]] \
  || die "public/build/manifest.json missing — build locally and commit it before deploying"

# ---------------------------------------------------------------- php deps ---
composer install --no-dev --optimize-autoloader --no-interaction --prefer-dist

# ---------------------------------------------------------------- database ---
# Down only across the migration, not the whole deploy: a maintenance page for
# ten minutes of composer is worse than one for ten seconds of schema change.
"$PHP" artisan down --render="errors::503" --retry=15 || true
"$PHP" artisan migrate --force --isolated
"$PHP" artisan up

# ------------------------------------------------------------------ caches ---
# Config is NOT cached. `config:cache` stops env() being read at all, and a
# changed .env then silently does nothing — recorded in the stale-snapshot
# register as the worst of that family. Routes, views and events are safe.
"$PHP" artisan route:cache
"$PHP" artisan view:cache
"$PHP" artisan event:cache

# The application cache is flushed on every deploy for the same reason the
# seeder flushes it: whatever is in there was computed against the previous
# release, and an empty snapshot in front of good data is invisible.
"$PHP" artisan cache:clear

"$PHP" artisan storage:link || true

# ------------------------------------------------------------------ workers --
# Horizon is told to finish the job in hand and exit; Supervisor restarts it on
# the new code. Never `kill -9` a worker mid-job.
"$PHP" artisan horizon:terminate || warn "horizon not running yet"

# ---------------------------------------------------------------- webserver --
if command -v nginx >/dev/null; then
  # Validated before reload, always. A bad config that reloads takes the site
  # down; a bad config that fails validation takes nothing down.
  sudo nginx -t || die "nginx config invalid — not reloading"
  sudo systemctl reload nginx
fi

# ------------------------------------------------------------------- verify --
# The deploy is not finished because the commands exited zero. It is finished
# when the site is observably correct.
log "running the smoke check"
"$PHP" artisan masar:smoke || die "smoke check failed — investigate before announcing the deploy"

log "deployed $(git rev-parse --short HEAD)"
